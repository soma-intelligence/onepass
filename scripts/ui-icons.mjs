const src = process.argv[2];
if (!src) throw new Error("usage: node scripts/ui-icons.mjs <material-symbols-svg-400 dir>");
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const drawable = join(root, "android/app/src/main/res/drawable");
mkdirSync(drawable, { recursive: true });

const paths = {};
for (const [name, sf, material] of ICONS) {
  const svg = readFileSync(join(src, "rounded", `${material}.svg`), "utf8");
  const d = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]).join(" ");
  if (!d || !svg.includes('viewBox="0 -960 960 960"')) throw new Error(`unexpected svg: ${material}`);
  paths[name] = d;
  // The Material viewBox starts at y = -960: the group moves it into the viewport.
  writeFileSync(
    join(drawable, `ic_${name}.xml`),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/ui-icons.mjs: Material Symbols "${material}" (Apache-2.0), for SF Symbol "${sf}". -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
        <path android:fillColor="#FF000000" android:pathData="${d}" />
    </group>
</vector>
`,
  );
}

const ts = `// Generated by scripts/ui-icons.mjs: Material Symbols (Apache-2.0), standing in
// for the iPhone app's SF Symbols. Path data on the 0 -960 960 960 viewBox.
export const ICON_PATHS = ${JSON.stringify(paths, null, 2)} as const;

export type IconName = keyof typeof ICON_PATHS;
`;
writeFileSync(join(root, "desktop/src/icons.ts"), ts);
