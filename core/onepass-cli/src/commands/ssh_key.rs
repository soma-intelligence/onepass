//! `onepass ssh-key`: SSH Key items, their host bookmarks and an OpenSSH
//! client configuration made from them (spec sections 6.4, 6.5 and 7).
//!
//! Keys are generated or imported here and stored as SSH Key items: the
//! private key as an unencrypted OpenSSH key (the vault encrypts it), the
//! public key, the fingerprint and the algorithm. `config` writes files in
//! a directory of the user's choosing and never touches `~/.ssh`.

