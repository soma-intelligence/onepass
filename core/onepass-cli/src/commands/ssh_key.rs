/// Largest private key file `import` reads.
const MAX_KEY_FILE: u64 = 1 << 20;
/// Default socket of `onepass ssh-agent`, in the data directory.
pub const AGENT_SOCKET: &str = "ssh-agent.sock";
/// First line of a generated `config`: a `config` that does not start
/// with it belongs to someone else and is never replaced.
const HEADER: &str =
    "# Generated by `onepass ssh-key config`: run it again after changing bookmarks.";
/// Largest existing `config` read to check its header.
const MAX_CONFIG_FILE: u64 = 1 << 20;
const KEY_TYPES: &str = "ed25519, ecdsa-p256, ecdsa-p384, ecdsa-p521, rsa-3072, rsa-4096";

#[derive(Subcommand)]
pub enum SshKeyCmd {
    /// Generate a key into a new SSH Key item.
    Generate {
        /// Key type: ed25519, ecdsa-p256, ecdsa-p384, ecdsa-p521, rsa-3072
        /// or rsa-4096.
        #[arg(long = "type", default_value = "ed25519", value_parser = parse_key_type)]
        key_type: KeyType,
        #[arg(long)]
        title: String,
        /// Target vault (default: Personnel, or the only vault).
        #[arg(long)]
        vault: Option<String>,
        /// Host bookmark (name or OpenSSH `Host` pattern), repeatable.
        #[arg(long = "host")]
        hosts: Vec<String>,
        /// Offer the key in `onepass ssh-agent`.
        #[arg(long)]
        agent: bool,
        /// Ask at every signature, never remember an approval.
        #[arg(long)]
        confirm_each_use: bool,
        /// Key comment (default: the title).
        #[arg(long)]
        comment: Option<String>,
    },
    /// Import a private key file (OpenSSH, encrypted or not; PEM PKCS#8,
    /// PKCS#1 or SEC1). The passphrase is asked on the terminal and not
    /// kept: the key is stored unencrypted in the vault.
    Import {
        file: PathBuf,
        #[arg(long)]
        title: String,
        /// Target vault (default: Personnel, or the only vault).
        #[arg(long)]
        vault: Option<String>,
        /// Host bookmark (name or OpenSSH `Host` pattern), repeatable.
        #[arg(long = "host")]
        hosts: Vec<String>,
        /// Offer the key in `onepass ssh-agent`.
        #[arg(long)]
        agent: bool,
        /// Ask at every signature, never remember an approval.
        #[arg(long)]
        confirm_each_use: bool,
        /// Key comment (default: the title).
        #[arg(long)]
        comment: Option<String>,
    },
    /// Print the public key of an SSH Key item (`authorized_keys` line).
    Public {
        /// Item id or title.
        key: String,
        #[arg(long)]
        vault: Option<String>,
    },
    /// Add or remove a host bookmark of an SSH Key item.
    #[command(subcommand)]
    Bookmark(BookmarkCmd),
    /// Write an OpenSSH client configuration for the bookmarked agent keys
    /// into a directory (never into ~/.ssh), and print the `Include` line
    /// to add to ~/.ssh/config.
    Config {
        /// Directory that receives `config` and the public keys.
        #[arg(long)]
        out: PathBuf,
        /// Agent socket (default: <data-dir>/ssh-agent.sock).
        #[arg(long)]
        socket: Option<PathBuf>,
    },
}

#[derive(Subcommand)]
pub enum BookmarkCmd {
    /// Bookmark a host for a key (no change if it already is).
    Add {
        /// Item id or title.
        key: String,
        /// Host name or OpenSSH `Host` pattern.
        host: String,
        #[arg(long)]
        vault: Option<String>,
    },
    /// Remove a host bookmark of a key.
    Remove {
        /// Item id or title.
        key: String,
        /// Host name or pattern, as bookmarked.
        host: String,
        #[arg(long)]
        vault: Option<String>,
    },
}

fn parse_key_type(s: &str) -> Result<KeyType, String> {
    s.parse().map_err(|_| {
        format!(
            "unknown key type '{s}', expected one of: {KEY_TYPES} \
             (RSA keys are generated with 3072 bits or more)"
        )
    })
}

/// What `generate` and `import` store besides the key.
struct NewKey {
    title: String,
    vault: Option<String>,
    hosts: Vec<String>,
    agent: bool,
    confirm_each_use: bool,
    comment: Option<String>,
}

pub fn run(ctx: &Ctx, cmd: SshKeyCmd) -> Result<(), CliError> {
    match cmd {
        SshKeyCmd::Generate {
            key_type,
            title,
            vault,
            hosts,
            agent,
            confirm_each_use,
            comment,
        } => {
            let new = NewKey {
                title,
                vault,
                hosts,
                agent,
                confirm_each_use,
                comment,
            };
            check_new(&new)?;
            let key = AgentKey::generate(key_type).map_err(key_error)?;
            save_new(ctx, &key, new)
        }
        SshKeyCmd::Import {
            file,
            title,
            vault,
            hosts,
            agent,
            confirm_each_use,
            comment,
        } => {
            let new = NewKey {
                title,
                vault,
                hosts,
                agent,
                confirm_each_use,
                comment,
            };
            check_new(&new)?;
            let key = import_file(&file)?;
            save_new(ctx, &key, new)
        }
        SshKeyCmd::Public { key, vault } => public(ctx, &key, vault.as_deref()),
        SshKeyCmd::Bookmark(BookmarkCmd::Add { key, host, vault }) => {
            check_host(&host)?;
            bookmark(ctx, &key, vault.as_deref(), |item| {
                Ok(if add_host(item, &host)? {
                    "bookmark added"
                } else {
                    "already bookmarked"
                })
            })
        }
        SshKeyCmd::Bookmark(BookmarkCmd::Remove { key, host, vault }) => {
            bookmark(ctx, &key, vault.as_deref(), |item| {
                if remove_host(item, host.trim()) {
                    Ok("bookmark removed")
                } else {
                    Err(CliError::not_found(format!(
                        "'{}' is not bookmarked",
                        host.trim()
                    )))
                }
            })
        }
        SshKeyCmd::Config { out, socket } => config(ctx, &out, socket),
    }
}

/// A key error as a usage error; its message never holds key material.
fn key_error(e: KeyError) -> CliError {
    CliError::usage(format!("SSH key: {e}"))
}

/// A host bookmark must fit on an OpenSSH `Host` line: one token, no quote,
/// no control character.
fn check_host(host: &str) -> Result<(), CliError> {
    if host_ok(host) {
        Ok(())
    } else {
        Err(CliError::usage(
            "a host bookmark is one host name or pattern, without spaces, quotes or control characters",
        ))
    }
}

fn host_ok(host: &str) -> bool {
    !host.is_empty()
        && !host
            .chars()
            .any(|c| c.is_whitespace() || c.is_control() || c == '"')
}

/// Text that ends up in key files (comments): one line.
fn check_comment(comment: &str) -> Result<(), CliError> {
    if comment.chars().any(char::is_control) {
        return Err(CliError::usage(
            "the key comment (or the title, its default) must not hold control characters",
        ));
    }
    Ok(())
}

/// Checks done before any prompt.
fn check_new(new: &NewKey) -> Result<(), CliError> {
    for h in &new.hosts {
        check_host(h)?;
    }
    check_comment(new.comment.as_deref().unwrap_or(&new.title))
}

/// The passphrase of an encrypted key file: `ONEPASS_DEV_SSH_PASSPHRASE`
/// only in a debug build with `ONEPASS_DEV_ALLOW_ENV_PASSWORD=1` (tests),
/// otherwise a masked prompt on the terminal.
fn read_passphrase() -> Result<Zeroizing<String>, CliError> {
    let dev = cfg!(debug_assertions);
    if crate::session::env_secrets_allowed()?
        && let Ok(p) = std::env::var("ONEPASS_DEV_SSH_PASSPHRASE")
    {
        return Ok(Zeroizing::new(p));
    }
    let no_tty = || {
        CliError::usage("the key is encrypted and there is no terminal to read its passphrase from")
    };
    if dev && std::env::var("ONEPASS_DEV_NO_TTY").as_deref() == Ok("1") {
        return Err(no_tty());
    }
    if !std::io::stdin().is_terminal() {
        return Err(no_tty());
    }
    let p = rpassword::prompt_password("Key passphrase: ").map_err(|_| no_tty())?;
    Ok(Zeroizing::new(p))
}

/// Reads and decodes a private key file, asking for its passphrase when it
/// is encrypted. Neither the file text nor the passphrase outlive the call.
fn import_file(path: &Path) -> Result<AgentKey, CliError> {
    let cannot = |what: &str| CliError::usage(format!("cannot read {}: {what}", path.display()));
    let f = fs::File::open(path).map_err(|e| cannot(&e.kind().to_string()))?;
    // Sized up front: a buffer that grows would leave copies of the key in
    // the freed allocations.
    let size = f
        .metadata()
        .map_err(|e| cannot(&e.kind().to_string()))?
        .len()
        .min(MAX_KEY_FILE);
    let capacity = usize::try_from(size).unwrap_or(0) + 1;
    let mut bytes = Zeroizing::new(Vec::with_capacity(capacity));
    f.take(MAX_KEY_FILE + 1)
        .read_to_end(&mut bytes)
        .map_err(|e| cannot(&e.kind().to_string()))?;
    if bytes.len() as u64 > MAX_KEY_FILE {
        return Err(cannot("too large for a key file"));
    }
    let text = match String::from_utf8(std::mem::take(&mut *bytes)) {
        Ok(s) => Zeroizing::new(s),
        Err(e) => {
            e.into_bytes().zeroize();
            return Err(cannot("not a text key file"));
        }
    };
    let passphrase = if is_encrypted(&text) {
        Some(read_passphrase()?)
    } else {
        None
    };
    AgentKey::from_private_text(&text, passphrase.as_deref().map(String::as_str)).map_err(key_error)
}

/// The template field `id` of an SSH Key item.
fn field_mut<'a>(item: &'a mut Item, id: &str) -> Result<&'a mut Field, CliError> {
    item.field_mut(id)
        .ok_or_else(|| CliError::usage(format!("the SSH Key item has no '{id}' field")))
}

fn yes_no(b: bool) -> FieldValue {
    FieldValue::Menu(if b { "yes" } else { "no" }.into())
}

/// Positions (section, field) of the `hosts` fields, in order.
fn host_slots(item: &Item) -> Vec<(usize, usize)> {
    item.sections
        .iter()
        .enumerate()
        .flat_map(|(si, s)| {
            s.fields
                .iter()
                .enumerate()
                .filter(|(_, f)| f.id == "hosts")
                .map(move |(fi, _)| (si, fi))
        })
        .collect()
}

fn host_value(f: &Field) -> Option<&str> {
    match &f.value {
        FieldValue::Text(h) if !h.trim().is_empty() => Some(h.trim()),
        _ => None,
    }
}

/// Adds a bookmark: the first `hosts` field if it is empty, otherwise a
/// copy of the field after the last one (the field is repeatable). Returns
/// false when the host is already bookmarked.
fn add_host(item: &mut Item, host: &str) -> Result<bool, CliError> {
    let host = host.trim();
    let slots = host_slots(item);
    if slots
        .iter()
        .any(|&(s, f)| host_value(&item.sections[s].fields[f]) == Some(host))
    {
        return Ok(false);
    }
    let value = FieldValue::Text(host.to_owned());
    match slots.as_slice() {
        [] => {
            // An item without the template field: take it from the template.
            let template = new_item(ItemType::SshKey, item.vault_id, "");
            let mut field = template
                .field("hosts")
                .cloned()
                .ok_or_else(|| CliError::usage("the SSH Key template has no 'hosts' field"))?;
            field.value = value;
            item.sections
                .first_mut()
                .ok_or_else(|| CliError::usage("the SSH Key item has no section"))?
                .fields
                .push(field);
        }
        [(s, f)] if host_value(&item.sections[*s].fields[*f]).is_none() => {
            item.sections[*s].fields[*f].value = value;
        }
        [.., (s, f)] => {
            let mut field = item.sections[*s].fields[*f].clone();
            field.value = value;
            item.sections[*s].fields.insert(f + 1, field);
        }
    }
    Ok(true)
}

/// Removes a bookmark. The last `hosts` field is emptied rather than
/// removed, so the template field stays. Returns false if it was absent.
fn remove_host(item: &mut Item, host: &str) -> bool {
    let slots = host_slots(item);
    let Some(&(s, f)) = slots
        .iter()
        .find(|&&(s, f)| host_value(&item.sections[s].fields[f]) == Some(host))
    else {
        return false;
    };
    if slots.len() == 1 {
        item.sections[s].fields[f].value = FieldValue::Empty;
    } else {
        item.sections[s].fields.remove(f);
    }
    true
}

/// Stores `key` as a new SSH Key item.
fn save_new(ctx: &Ctx, key: &AgentKey, new: NewKey) -> Result<(), CliError> {
    let comment = new.comment.clone().unwrap_or_else(|| new.title.clone());
    let value = SshKeyValue {
        private_pem: key.to_openssh_private(&comment).map_err(key_error)?,
        public_openssh: key.public_openssh(&comment),
        fingerprint_sha256: key.fingerprint(),
    };
    let fingerprint = value.fingerprint_sha256.clone();
    let public_line = value.public_openssh.clone();
    with_session(ctx, |repo| {
        let vaults = all(repo)?;
        let vi = match new.vault.as_deref() {
            Some(v) => find_vault(&vaults, v)?,
            None => find_vault(&vaults, "Personnel")
                .or_else(|e| if vaults.len() == 1 { Ok(0) } else { Err(e) })?,
        };
        let mut item = new_item(ItemType::SshKey, vaults[vi].id, &new.title);
        field_mut(&mut item, "private_key")?.value = FieldValue::SshKey(value);
        field_mut(&mut item, "algorithm")?.value = FieldValue::Menu(key.algorithm_name().into());
        if !comment.is_empty() {
            field_mut(&mut item, "comment")?.value = FieldValue::Text(comment);
        }
        field_mut(&mut item, "use_in_agent")?.value = yes_no(new.agent);
        field_mut(&mut item, "confirm_each_use")?.value = yes_no(new.confirm_each_use);
        for h in &new.hosts {
            add_host(&mut item, h)?;
        }
        let id = item.id;
        stored(repo.save_item(&vaults[vi], item))?;
        if ctx.json {
            crate::out!(
                "{}",
                json!({
                    "id": id.to_string(),
                    "fingerprint": fingerprint,
                    "public_key": public_line,
                })
            );
        } else {
            crate::out!("created {id}");
            crate::out!("{fingerprint}");
        }
        Ok(())
    })
}

/// The live SSH Key item `key`, and the index of its vault.
fn find_ssh_item(
    repo: &mut onepass_core::repo::Repository<onepass_core::store::SqliteStore>,
    vaults: &[onepass_core::vault::Vault],
    vault: Option<&str>,
    key: &str,
) -> Result<(usize, Item), CliError> {
    let (vi, item) = find_item(repo, vaults, vault, key)?;
    if item.item_type != ItemType::SshKey {
        return Err(CliError::usage(format!("'{key}' is not an SSH key")));
    }
    Ok((vi, item))
}

fn public(ctx: &Ctx, key: &str, vault: Option<&str>) -> Result<(), CliError> {
    with_session(ctx, |repo| {
        let vaults = all(repo)?;
        let (_, item) = find_ssh_item(repo, &vaults, vault, key)?;
        let Some(FieldValue::SshKey(v)) = item.field("private_key").map(|f| &f.value) else {
            return Err(CliError::usage(format!("'{key}' holds no SSH key")));
        };
        if ctx.json {
            crate::out!("{}", json!({ "public_key": v.public_openssh }));
        } else {
            crate::out!("{}", v.public_openssh);
        }
        Ok(())
    })
}

fn bookmark(
    ctx: &Ctx,
    key: &str,
    vault: Option<&str>,
    change: impl FnOnce(&mut Item) -> Result<&'static str, CliError>,
) -> Result<(), CliError> {
    with_session(ctx, |repo| {
        let vaults = all(repo)?;
        let (vi, mut item) = find_ssh_item(repo, &vaults, vault, key)?;
        let before = item.clone();
        let said = change(&mut item)?;
        if item != before {
            item.updated_at = OffsetDateTime::now_utc();
            stored(repo.save_item(&vaults[vi], item))?;
        }
        crate::out!("{said}");
        Ok(())
    })
}

/// `p` made absolute with `.` and `..` resolved lexically, before any
/// file system access: every later action uses this path.
fn normalize(p: &Path) -> Result<PathBuf, CliError> {
    let mut out = PathBuf::new();
    for c in std::path::absolute(p)?.components() {
        match c {
            Component::ParentDir => {
                out.pop();
            }
            Component::CurDir => {}
            other => out.push(other),
        }
    }
    Ok(out)
}

/// A normalized path with its longest existing ancestor resolved through
/// symlinks (the rest does not exist, so it holds no symlink).
fn resolve(p: &Path) -> PathBuf {
    let mut rest = Vec::new();
    let mut cur = p;
    loop {
        if let Ok(mut r) = fs::canonicalize(cur) {
            r.extend(rest.iter().rev());
            return r;
        }
        match (cur.file_name(), cur.parent()) {
            (Some(name), Some(parent)) => {
                rest.push(name.to_owned());
                cur = parent;
            }
            _ => return p.to_path_buf(),
        }
    }
}

/// Whether `out` names `$HOME/.ssh`, directly, through `..` or through
/// symlinks.
fn is_home_ssh(out: &Path) -> Result<bool, CliError> {
    let Some(home) = std::env::var_os("HOME") else {
        return Ok(false);
    };
    let ssh = normalize(&PathBuf::from(home).join(".ssh"))?;
    let out = normalize(out)?;
    Ok(out == ssh || resolve(&out) == resolve(&ssh))
}

fn effective_uid() -> u32 {
    // SAFETY: geteuid takes no argument, cannot fail and has no side effect.
    unsafe { libc::geteuid() }
}

/// Checks an output directory without changing it. A missing directory is
/// fine (it is created 0700); an existing one must be a directory of this
/// user with mode 0700, and its `config`, if any, a regular file that
/// starts with [`HEADER`]. Returns whether the directory exists.
fn check_out_dir(out: &Path) -> Result<bool, CliError> {
    let m = match fs::metadata(out) {
        Ok(m) => m,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(false),
        Err(e) => return Err(e.into()),
    };
    let shown = out.display();
    if !m.is_dir() {
        return Err(CliError::usage(format!("{shown} is not a directory")));
    }
    if m.uid() != effective_uid() || m.permissions().mode() & 0o777 != 0o700 {
        return Err(CliError::usage(format!(
            "{shown} exists but is not a 0700 directory of yours; \
             pass a new directory (it is created 0700) or fix its mode"
        )));
    }
    let config = out.join("config");
    match fs::symlink_metadata(&config) {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(true),
        Err(e) => return Err(e.into()),
        Ok(cm) if !cm.file_type().is_file() => {
            return Err(CliError::usage(format!(
                "{} is not a regular file: refusing to replace it",
                config.display()
            )));
        }
        Ok(_) => {}
    }
    let mut head = String::new();
    fs::File::open(&config)?
        .take(MAX_CONFIG_FILE)
        .read_to_string(&mut head)
        .ok();
    if head.lines().next() != Some(HEADER) {
        return Err(CliError::usage(format!(
            "{} was not generated by onepass: refusing to replace it",
            config.display()
        )));
    }
    Ok(true)
}

/// A path as an `ssh_config` argument: quoted, `%` escaped (OpenSSH expands
/// `%` tokens in these options). Quotes, `$` (environment expansion) and
/// control characters are refused.
fn config_path(p: &Path) -> Result<String, CliError> {
    let s = p
        .to_str()
        .ok_or_else(|| CliError::usage(format!("{} is not valid UTF-8", p.display())))?;
    if s.chars().any(|c| c.is_control() || c == '"' || c == '$') {
        return Err(CliError::usage(format!(
            "{} cannot be written in an ssh config (quote, $ or control character)",
            p.display()
        )));
    }
    Ok(format!("\"{}\"", s.replace('%', "%%")))
}

/// File name stem of a public key: the fingerprint without `SHA256:`, with
/// `/` and `+` made file-name safe.
fn pub_stem(fingerprint: &str) -> String {
    fingerprint
        .trim_start_matches("SHA256:")
        .replace('/', "_")
        .replace('+', "-")
}

/// One line of text from vault data (titles): control characters become
/// spaces, so they cannot add lines to a file.
fn one_line(s: &str) -> String {
    s.chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect()
}

/// The `authorized_keys` line of a key blob, commented with `comment`.
fn public_line(k: &KeyInfo) -> Result<String, CliError> {
    let bad = || CliError::usage("an agent key has a malformed public key");
    let len_bytes: [u8; 4] = k
        .public_blob
        .get(..4)
        .and_then(|b| b.try_into().ok())
        .ok_or_else(bad)?;
    let len = u32::from_be_bytes(len_bytes) as usize;
    let algorithm = k
        .public_blob
        .get(4..4 + len)
        .and_then(|b| std::str::from_utf8(b).ok())
        .ok_or_else(bad)?;
    Ok(format!(
        "{algorithm} {} {}",
        BASE64.encode(&k.public_blob),
        one_line(&k.title)
    ))
}

/// Writes `contents` to `path` (mode 0600) through a temporary file.
fn write_private(path: &Path, contents: &str) -> Result<(), CliError> {
    let mut tmp = path.as_os_str().to_owned();
    tmp.push(".tmp");
    let tmp = PathBuf::from(tmp);
    let _ = fs::remove_file(&tmp);
    let mut f = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(&tmp)?;
    f.write_all(contents.as_bytes())?;
    f.sync_all()?;
    fs::rename(&tmp, path)?;
    fs::set_permissions(path, fs::Permissions::from_mode(0o600))?;
    Ok(())
}

/// The generated `config` text and the public key files it names.
fn render_config(
    keys: &[KeyInfo],
    out: &Path,
    socket: &str,
) -> Result<(String, Vec<(PathBuf, String)>), CliError> {
    let mut text = format!(
        "{HEADER}\n# Include this file from ~/.ssh/config; onepass never edits that file.\n"
    );
    let mut files = Vec::new();
    for k in keys {
        let hosts: Vec<&str> = k
            .hosts
            .iter()
            .map(String::as_str)
            .filter(|h| host_ok(h))
            .collect();
        if hosts.is_empty() {
            continue;
        }
        let pub_path = out.join(format!("{}.pub", pub_stem(&k.fingerprint)));
        text.push_str(&format!(
            "\n# {} ({})\nHost {}\n    IdentityFile {}\n    IdentitiesOnly yes\n    IdentityAgent {}\n",
            one_line(&k.title),
            k.fingerprint,
            hosts.join(" "),
            config_path(&pub_path)?,
            socket,
        ));
        files.push((pub_path, format!("{}\n", public_line(k)?)));
    }
    Ok((text, files))
}

fn config(ctx: &Ctx, out: &Path, socket: Option<PathBuf>) -> Result<(), CliError> {
    let out = normalize(out)?;
    // `<out>/config` must never be the user's own ~/.ssh/config.
    let home_ssh = || {
        CliError::usage(
            "refusing to write into ~/.ssh: choose another directory and Include its config",
        )
    };
    if is_home_ssh(&out)? {
        return Err(home_ssh());
    }
    let socket = normalize(&socket.unwrap_or_else(|| ctx.data_dir.join(AGENT_SOCKET)))?;
    let socket_arg = config_path(&socket)?;
    let config_file = out.join("config");
    let include = config_path(&config_file)?;
    // Before the password prompt, so a refused directory costs nothing.
    let existed = check_out_dir(&out)?;
    let keys = with_session(ctx, |repo| stored(ssh_keys_of(repo)))?;
    let (text, files) = render_config(&keys, &out, &socket_arg)?;
    if !existed {
        fs::DirBuilder::new()
            .recursive(true)
            .mode(0o700)
            .create(&out)?;
        // Only the directory made here is tightened (the mode above is
        // filtered by the umask).
        fs::set_permissions(&out, fs::Permissions::from_mode(0o700))?;
    }
    // Again now that the directory exists (`is_home_ssh` then resolves the
    // whole path): through any symlink it must still not be ~/.ssh, and it
    // must still be ours.
    if is_home_ssh(&out)? {
        return Err(home_ssh());
    }
    check_out_dir(&out)?;
    for (path, contents) in &files {
        write_private(path, contents)?;
    }
    write_private(&config_file, &text)?;
    if ctx.json {
        crate::out!(
            "{}",
            json!({ "config": config_file.display().to_string(), "keys": files.len(), "include": format!("Include {include}") })
        );
    } else {
        crate::out!("wrote {} ({} keys)", config_file.display(), files.len());
        crate::out!("add this line to ~/.ssh/config (onepass does not edit it):");
        crate::out!("Include {include}");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use onepass_core::Id;

    fn hosts_of(item: &Item) -> Vec<FieldValue> {
        host_slots(item)
            .into_iter()
            .map(|(s, f)| item.sections[s].fields[f].value.clone())
            .collect()
    }

    fn text(s: &str) -> FieldValue {
        FieldValue::Text(s.into())
    }

    #[test]
    fn bookmarks_fill_then_copy_then_empty_the_template_field() {
        let mut item = new_item(ItemType::SshKey, Id::new(), "k");
        assert_eq!(hosts_of(&item), [FieldValue::Empty]);
        assert!(add_host(&mut item, " a.test ").unwrap());
        assert_eq!(hosts_of(&item), [text("a.test")]);
        assert!(add_host(&mut item, "*.b.test").unwrap());
        assert!(!add_host(&mut item, "a.test").unwrap());
        assert_eq!(hosts_of(&item), [text("a.test"), text("*.b.test")]);
        // The copies stay next to each other and repeatable.
        let (s, f) = host_slots(&item)[1];
        assert!(item.sections[s].fields[f].repeatable);
        assert_eq!(host_slots(&item)[0].1 + 1, f);
        assert!(!remove_host(&mut item, "c.test"));
        assert!(remove_host(&mut item, "a.test"));
        assert_eq!(hosts_of(&item), [text("*.b.test")]);
        assert!(remove_host(&mut item, "*.b.test"));
        assert_eq!(hosts_of(&item), [FieldValue::Empty]);
    }

    #[test]
    fn hosts_and_paths_that_would_break_the_config_are_refused() {
        for ok in ["git.example.test", "*.example.test", "!x.test", "10.0.0.?"] {
            assert!(host_ok(ok), "{ok}");
        }
        for bad in ["", "a b", "a\tb", "a\"b", "a\nHost *"] {
            assert!(!host_ok(bad), "{bad:?}");
        }
        assert_eq!(
            config_path(Path::new("/a/b 1%/c")).unwrap(),
            "\"/a/b 1%%/c\""
        );
        for bad in ["/a\"b", "/a/$HOME", "/a\nb"] {
            assert!(config_path(Path::new(bad)).is_err(), "{bad:?}");
        }
        assert_eq!(pub_stem("SHA256:ab/c+d"), "ab_c-d");
        assert_eq!(one_line("a\nIdentityFile x"), "a IdentityFile x");
    }

    #[test]
    fn paths_are_normalized_before_any_file_system_access() {
        assert_eq!(
            normalize(Path::new("/h/missing/../.ssh/./")).unwrap(),
            Path::new("/h/.ssh")
        );
        assert_eq!(normalize(Path::new("/../a")).unwrap(), Path::new("/a"));
        assert!(normalize(Path::new("rel")).unwrap().is_absolute());
    }

    #[test]
    fn key_types_and_their_refusal() {
        assert_eq!(parse_key_type("ed25519").unwrap(), KeyType::Ed25519);
        assert_eq!(parse_key_type("rsa-4096").unwrap(), KeyType::Rsa4096);
        let e = parse_key_type("rsa-2048").unwrap_err();
        assert!(e.contains("rsa-2048") && e.contains("rsa-3072"), "{e}");
    }

    #[test]
    fn rendered_config_skips_keys_without_valid_hosts() {
        let key = AgentKey::generate(KeyType::Ed25519).unwrap();
        let info = |title: &str, hosts: &[&str]| KeyInfo {
            item_id: Id::new().to_string(),
            vault_id: Id::new().to_string(),
            vault_name: "Personnel".into(),
            title: title.into(),
            public_blob: key.public_blob(),
            fingerprint: key.fingerprint(),
            confirm_each_use: false,
            hosts: hosts.iter().map(|h| h.to_string()).collect(),
        };
        let keys = [
            info("A\nHost *", &["a.test", "bad host"]),
            info("None", &[]),
            info("Bad only", &["x y"]),
        ];
        let (text, files) = render_config(&keys, Path::new("/o"), "\"/s\"").unwrap();
        assert_eq!(files.len(), 1);
        assert!(text.contains("\nHost a.test\n"), "{text}");
        // The title's newline did not start a `Host *` line.
        assert!(text.contains("# A Host * ("), "{text}");
        assert!(!text.lines().any(|l| l.starts_with("Host *")), "{text}");
        assert!(text.contains("IdentityAgent \"/s\""));
        let line = &files[0].1;
        assert_eq!(
            line.trim_end(),
            format!("{} A Host *", key.public_openssh(""))
        );
    }
}
