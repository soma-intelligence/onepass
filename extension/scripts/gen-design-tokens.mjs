// Mirrors the design tokens of src/ui/theme.css into src/shared/design-tokens.ts, which the content
// script imports (it cannot read the extension stylesheet, its UI lives in closed shadow roots).
// Usage: node scripts/gen-design-tokens.mjs [--check]
//   (no flag) writes the file; --check exits 1 when the committed file differs from theme.css.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const CSS = join(root, "src/ui/theme.css");
const OUT = join(root, "src/shared/design-tokens.ts");
/** Variable families the content script needs. */
const FAMILY = /^(glyph-|frame-|accent(-|$)|r-|space-)/;

/** Body of the first `{ ... }` block after `header` (braces balanced). */
function block(css, header, from = 0) {
  const at = css.indexOf(header, from);
  if (at < 0) throw new Error(`missing ${header} in theme.css`);
  const open = css.indexOf("{", at);
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === "{") depth++;
    if (css[i] === "}" && --depth === 0) return css.slice(open + 1, i);
  }
  throw new Error(`unbalanced ${header}`);
}

/** Declared custom properties of a block body, minus the leading `--`, filtered to the mirrored families. */
function vars(body) {
  const out = {};
  for (const m of body.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/g)) {
    if (FAMILY.test(m[1])) out[m[1]] = m[2].trim();
  }
  return out;
}

export function generate(css = readFileSync(CSS, "utf8")) {
  const dark = vars(block(css, ":root {"));
  const lightMedia = block(css, "@media (prefers-color-scheme: light)");
  // The light theme only overrides: start from the dark values.
  const light = { ...dark, ...vars(block(lightMedia, ":root {")) };
  const lit = (o) => "{\n" + Object.entries(o).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n") + "\n  }";
  return `// Generated by scripts/gen-design-tokens.mjs from src/ui/theme.css. Do not edit.
export const DESIGN_TOKENS: {
  dark: Readonly<Record<string, string>>;
  light: Readonly<Record<string, string>>;
} = {
  dark: ${lit(dark)},
  light: ${lit(light)},
};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = generate();
  if (process.argv.includes("--check")) {
    let cur = "";
    try { cur = readFileSync(OUT, "utf8"); } catch { /* missing counts as different */ }
    if (cur !== next) {
      console.error("src/shared/design-tokens.ts is out of date: run node scripts/gen-design-tokens.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, next);
  }
}
